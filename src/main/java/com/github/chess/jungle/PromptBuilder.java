package com.github.chess.jungle;

import com.github.chess.jungle.web.dto.AiMoveRequest;
import com.github.chess.jungle.web.dto.LegalMove;
import org.springframework.stereotype.Component;

/**
 * 构造发给大模型的提示词。
 * <p>
 * 系统提示词固定为棋手人设加通用规则，每一手都完全相同，便于命中提示词缓存；
 * 用户提示词才携带当轮局面与合法着法编号。
 * <p>
 * 这里的文字是按「压住推理模型的思考长度」来写的，不是按人类读着顺口来写的。
 * 起因是一次实测：effort 配 low 的一手棋花了 887 秒，34186 个输出 token 里有 34152 个是思考，
 * 真正的答案只有 34 个。翻思考过程，token 主要烧在两件事上，下面两条常量分别对着它们：
 * {@link #RULES} 对着「反复重推规则」，{@link #THINKING_PACE} 对着「无边界地自由搜索」。
 * <p>
 * 有一条线不能越过：提示词只给事实和思考节奏，不给棋理。「先入巢再吃子再推进」
 * 这类优先级确实能让模型想得更快，但那等于把兜底启发式换个地方又写了一遍，
 * 下出来的是我们的棋，不是模型的棋。关掉思考同样不行，实测棋力掉得太多。
 * 所以速度只从两处省：规则事实摆清楚不让它现推，思考的宽度、深度、长度给出上限。
 * 实测还发现规则里写错或写含糊的地方比节奏更费时间——模型会在矛盾处反复核对，
 * 所以改规则文本时对照前端 rules.ts 逐条核一遍。
 *
 * @author yaoyuquan
 */
@Component
public class PromptBuilder {

    /**
     * 规则文本，写成可直接查表的判定式，而不是人类习惯的简写。
     * <p>
     * 实测里模型把大量思考花在把简写还原成事实上，而且还原错了好几次又回头改：
     * 「河流占据 B6~C4」它猜了三轮才确定是个矩形；「高等级可吃同级及以下」让它两次回头
     * 确认虎到底能不能吃鼠；水中的鼠能不能吃岸上的子，它推到一半才想起来，
     * 并因此推翻了前面整段结论。这些都是规则的确定性推论，让模型每一手现推一遍纯属浪费。
     * <p>
     * 所以这里把能枚举的全部枚举：水域列到格、跳河列出全部起落点对、陷阱与兽巢列出坐标，
     * 并把「没有别的例外」这种否定式结论直接写死，省得模型自己去确认一遍。
     * <p>
     * 这些坐标全都能从规则本身推出来，不是后端新增的规则知识，规则实现仍然只有前端一份。
     * <p>
     * 兽力顺序必须与前端 constants.ts 一致：3 是狼、4 是狗，狗大于狼。这里曾写成「狼4 &gt; 狗3」，
     * 模型读到候选里的「狗吃狼」与规则对不上，只能在思考里反复核对，白烧 token。
     * <p>
     * 陷阱那条同理。原文是「踩进对方陷阱的棋子失去全部威势」，实测模型把「失去威势」读成了
     * 「它也不能吃子」，于是认定「狗进 C1 吃狼不成立」，放着赢棋的路不走。前端 canCapture
     * 只看守方是否站在攻方的陷阱里，攻方站在哪不影响它吃子，所以这里把「唯一的效果」写死。
     */
    private static final String RULES = """
            斗兽棋规则要点：
            1. 棋盘 7 列（A~G）× 9 行（1~9），红方底线在第 9 行，蓝方底线在第 1 行，蓝方先行。
            2. 兽力由大到小：象8 > 狮7 > 虎6 > 豹5 > 狗4 > 狼3 > 猫2 > 鼠1。
               高等级可吃同级及以下。唯一的例外是鼠与象：鼠能吃象，象不能吃鼠。
               除这一条外没有任何别的例外——狮、虎、豹、狗、狼、猫都能吃鼠。
            3. 水域共 12 格：B4 B5 B6 C4 C5 C6 E4 E5 E6 F4 F5 F6。只有鼠能进入水域。
            4. 鼠在水中时：吃不到岸上的棋子，也不会被岸上的棋子吃；从水里出来只能走到空格，
               不能在出水的同时吃子。
            5. 狮与虎可以跳过整片水域，直接落到对岸的陆地格，落点如下：
               横跨左河：A4↔D4、A5↔D5、A6↔D6
               横跨右河：D4↔G4、D5↔G5、D6↔G6
               纵跨左河：B3↔B7、C3↔C7
               纵跨右河：E3↔E7、F3↔F7
               跨越路径上只要有任何棋子（包括水里的鼠）就不能跳。除上列之外没有别的跳法。
            6. 陷阱：红方陷阱 C9、D8、E9，蓝方陷阱 C1、D2、E1。
               棋子站在对方陷阱里时，对方任意棋子都能吃它（包括鼠）。这是陷阱唯一的效果：
               它自己吃子不受影响，照样按兽力吃；走进对方陷阱的同时也可以吃掉站在那里的棋子。
               站在己方陷阱里不受任何影响。
            7. 兽巢：红巢 D9，蓝巢 D1。任何棋子都不能走进己方兽巢，走进对方兽巢即刻获胜。
               D9 的三个邻格是 C9、D8、E9，全部是红方陷阱；D1 的三个邻格 C1、D2、E1 同理。
               也就是说，进兽巢必定要先经过对方的一个陷阱。
            8. 一方棋子被吃光或无子可动也判负。
            """;

    /**
     * 棋手人设。
     * <p>
     * 以前这里还写着「不做亏损的换子、推进时留好退路、留意对方的鼠和狮虎」，
     * 那是在替模型下棋，已删掉。怎么下留给模型自己判断，这里只交代身份和任务。
     */
    private static final String PERSONA = """
            你是一位斗兽棋棋手，正在下一盘快棋，轮到你从给出的候选着法里选一手。""";

    /**
     * 双方还没有接触时的思考字数上限，写进 {@link #THINKING_PACE}。
     */
    static final int QUIET_CHAR_BUDGET = 200;

    /**
     * 已经接触时的思考字数上限，写进 {@link #THINKING_PACE}。
     * <p>
     * 这两个数是速度和棋力之间的旋钮：嫌慢往下调，嫌下得臭往上调。
     * mimo 并不逐字守它们——复杂残局照样能想出几千字——但给了具体数字，
     * 它就有一个「差不多该停了」的参照；只说「简短思考」的话，简短可以是任意长。
     */
    static final int CONTACT_CHAR_BUDGET = 600;

    /**
     * 思考节奏，只发给对话型模型。
     * <p>
     * 实测里模型烧掉最多 token 的不是规则，是没有停下来的理由：它把 24 条候选逐条展开，
     * 为开局设计了七八步的长远计划，然后反复自我推翻——思考过程里出现了
     * 「I keep going in circles」「analysis paralysis」「Time to decide」之后又继续想。
     * 根因是「选出最好的一手」这种最高级说法本身没有终止条件，穷举到死都不算违背指令。
     * <p>
     * 这段话是拿 mimo-v2.6-flash（effort=low）在同一批局面上逐版实测挑出来的，
     * 局面里有一个专门的试金石：象吃狼看着是最大的吃子，但落点旁边是对方的鼠，吃完就被鼠反吃，
     * 豹吃同一只狼才安全。各版的教训写在下面，改这段之前先看一遍：
     * <ul>
     *   <li>棋理清单（入巢 &gt; 白吃 &gt; 逃子 &gt; 推进，命中即返回）：开局快，但那是在照单执行我们的棋；
     *       清单覆盖不到的残局反而最慢——它会反复纠结「这手算不算第几条」，一手想了 7000 token
     *       还走了一步闲棋。</li>
     *   <li>每手推四步：棋力好，但「四步」会诱导它去找杀棋，中局、残局都出现过 100 秒以上的长尾。</li>
     *   <li>只看对方一个应手：残局反而失控到上万 token——局面需要深算时，禁止深算只会让它原地打转。</li>
     *   <li>按局面分平静 / 接触，但接触时的要求写得软：它会判断出「接触」，然后照样只想一两句，
     *       试金石三次里错两次。</li>
     *   <li>平静局面凭棋感直接走，接触局面必须推「我 → 对方最强应手 → 我」三步，
     *       并逐个检查落点四周的对方棋子。试金石 4/4，开局 3~6 秒，中局与战术局面 7~20 秒。
     *       但一上真实对局就露了底：它从来不防守自己的兽巢。对方的豹沿 D 列一路走进兽巢，
     *       它连着几手的理由都是「双方未接触」——「接触」只按棋子相邻来判，
     *       逼近兽巢的子不贴着谁，于是整段检查都被跳过；列对方应手时也只想到吃子，
     *       从没想过对方会直接走进它的兽巢。</li>
     *   <li>现在这版：用户提示词里补一句「你的兽巢是 D1，对方走进去你就输」（原来只写了要打进哪个巢）；
     *       「接触」把「任何一方有子离对方兽巢三步以内」也算进去；找对方应手时先看有没有子能一步进我的巢。
     *       守巢局面（唯二解）3/3 走对，上一版同一局面去冲对方的巢，直接输掉。</li>
     * </ul>
     * 「怎么走都挡不住就别再找」对着的是实战里卡住的那一手：对方的子已经贴着兽巢、谁都够不着它，
     * 模型在十一个候选里找一个不存在的解，一手想了 200 多秒。加上这句之后同一局面稳定在 30 秒内。
     * 压不住的是兽巢附近的复杂残局：每一版都出现过 100 秒以上、上万 token 的思考，
     * 翻过程是它已经写出了决定，又回头把整条杀法重算一遍。试过让它写下「定：编号」就收笔，
     * 没用——它只在真想完时才写。这段长尾靠提示词解决不了，要压只能在调用侧动手。
     * 「逐个检查落点四周的对方棋子、对照规则例外」是这版里最要紧的一句：
     * 没有它时模型知道要找对方的应手，却会只看远处的大子，漏掉贴身的鼠。
     * 它讲的是怎么检查，不是该走哪步，不针对任何局面，所以不算在教棋。
     * <p>
     * 「不要去找完整的取胜路线」对着的是兽巢附近的局面：模型一看到能进巢就会开始穷举杀法，
     * 这句不能完全压住它，但能让长尾短很多。「快棋」这个设定是整段的由头，
     * 用它来框住思考，比一条条列禁令更容易被模型当成自己的节奏。
     */
    private static final String THINKING_PACE = """
            这是快棋，每一手的思考时间有限。先看一眼局面有没有接触，再按对应的方式想。
            接触指：双方有棋子已经能互相够到，或者任何一方有棋子离对方兽巢三步以内。
            - 还没有接触：凭棋感直接选一手，不推演变化，思考控制在 %d 字以内。
            - 已经接触：凭棋感圈出最有希望的两手，每一手都要沿一条主变推三步：
              我走这手 → 对方最强的应手 → 我的下一手。每一步只取最可能的那一着，不展开分支。
              找对方最强的应手时，先看对方有没有棋子能一步走进我的兽巢，
              再把落点四周的对方棋子逐个过一遍，并对照规则里的例外（鼠吃象、狮虎跳河）。
              推完三步还看不清的，就按已经看到的判断，不再加深；不要去找完整的取胜路线。
              思考控制在 %d 字以内。
            如果看出怎么走都挡不住对方下一手取胜，或者怎么走都要丢子，这一手就是没有好解，
            不要继续找，直接从已经看过的着法里选一手。
            推演时用「狮A9→A8」「虎吃狼D5」这样的简写记着法，不写整句。
            选定之后不再推翻重算；拿不准时取第一眼更看好的那手。
            规则以上面写的为准，不需要再核对或重新推导。""".formatted(QUIET_CHAR_BUDGET, CONTACT_CHAR_BUDGET);

    /**
     * 输出约定。
     * <p>
     * 末尾那句「不要复述分析过程」是给推理模型的：正文里再讲一遍思考，既拖慢又可能
     * 把 JSON 挤到 token 上限之外。
     */
    private static final String OUTPUT_CONTRACT = """
            你必须从给出的候选着法编号中选择恰好一个，并以 json 返回：
            {"index": <候选着法的编号>, "reason": "<一句中文理由，不超过 40 字>"}
            index 必须是候选列表中真实存在的编号，不得自创着法或返回列表之外的数字。
            只输出这一个 json 对象，不要附加任何解释，不要复述分析过程，也不要套代码块围栏。
            """;

    /**
     * 系统提示词：棋手人设 + 规则 + 思考节奏 + 输出约定。每手不变，可被提示词缓存复用。
     */
    public String buildSystemPrompt() {
        return PERSONA +
                "\n\n" + RULES +
                '\n' + THINKING_PACE +
                "\n\n" + OUTPUT_CONTRACT;
    }

    /**
     * 用户提示词：当轮局面 + 编号后的合法着法。
     */
    public String buildUserPrompt(AiMoveRequest request, String boardText) {
        String side = request.side();
        StringBuilder sb = new StringBuilder();
        sb.append("你执").append(JungleBoard.sideName(side))
                .append("，对手是").append(JungleBoard.sideName(JungleBoard.opposite(side))).append("。");
        sb.append("你要打进").append(JungleBoard.sideName(JungleBoard.opposite(side)))
                .append("的兽巢（").append(JungleBoard.toCoord(JungleBoard.targetDenRow(side), 3)).append("）。\n");
        // 只写要打进哪个巢时，模型从不防守自己的巢：它把己方兽巢当成一个普通的地形格，
        // 列对方应手时想不到对方会走进去。规则第 7 条是第三人称的，得在这里落到「你」身上
        String ownDen = JungleBoard.toCoord(JungleBoard.targetDenRow(JungleBoard.opposite(side)), 3);
        sb.append("你的兽巢是 ").append(ownDen).append("：对方任何棋子走进 ").append(ownDen)
                .append("，你立即输棋。\n");
        if (request.moveNumber() != null) {
            sb.append("当前是第 ").append(request.moveNumber()).append(" 手。\n");
        }
        sb.append("\n当前局面：\n").append(boardText).append('\n');
        sb.append("\n候选着法（只能从中选一个编号）：\n");
        for (LegalMove move : request.legalMoves()) {
            sb.append('[').append(move.i()).append("] ").append(describe(move)).append('\n');
        }

        // 收尾这句刻意不写「选出你认为最好的一手」：最高级说法没有终止条件，
        // 实测下来模型会一直找下去。指回快棋节奏，它才有停下来的依据
        sb.append("\n按快棋的节奏想，走出你这一手。");
        return sb.toString();
    }

    /**
     * 着法描述。前端已经给了中文文本，缺失时用坐标兜底。
     */
    private String describe(LegalMove move) {
        if (move.text() != null && !move.text().isBlank()) {
            return move.text();
        }
        return JungleBoard.toCoord(move.from().get(0), move.from().get(1))
                + "→" + JungleBoard.toCoord(move.to().get(0), move.to().get(1));
    }
}
